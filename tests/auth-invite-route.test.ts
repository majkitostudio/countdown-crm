import { NextRequest } from "next/server";
import { beforeEach, describe, expect, it, vi } from "vitest";

const mocks = vi.hoisted(() => ({ getUser: vi.fn(), verifyOtp: vi.fn(), setAll: vi.fn() }));
vi.mock("@supabase/ssr", () => ({
  createServerClient: (_url: string, _key: string, options: { cookies: { setAll: (cookies: never[]) => void } }) => {
    mocks.setAll.mockImplementation(options.cookies.setAll);
    return { auth: { getUser: mocks.getUser, verifyOtp: mocks.verifyOtp } };
  },
}));
vi.mock("@/lib/supabase/config", () => ({
  getSupabasePublicConfig: () => ({ url: "https://example.supabase.co", anonKey: "test" }),
}));

import { POST } from "@/app/auth/invite/confirm/route";

// SHA-224 as generated by Supabase Auth, represented in lowercase hex.
const token = "0123456789abcdef".repeat(3) + "01234567";
function request(body: unknown, origin = "https://crm.example") {
  return new NextRequest("https://crm.example/auth/invite/confirm", {
    method: "POST",
    headers: { origin, "content-type": "application/json" },
    body: JSON.stringify(body),
  });
}

beforeEach(() => {
  vi.clearAllMocks();
  mocks.getUser.mockResolvedValue({ data: { user: null }, error: { name: "AuthSessionMissingError" } });
  mocks.verifyOtp.mockResolvedValue({ error: null });
});

describe("invite confirmation", () => {
  it("verifies invite and returns session cookies", async () => {
    mocks.verifyOtp.mockImplementationOnce(async () => {
      mocks.setAll([{ name: "sb-auth-token", value: "session", options: { path: "/", httpOnly: true } }]);
      return { error: null };
    });
    const response = await POST(request({ token_hash: token }));
    expect(mocks.verifyOtp).toHaveBeenCalledWith({ token_hash: token, type: "invite" });
    expect(response.status).toBe(200);
    expect(response.cookies.get("sb-auth-token")?.value).toBe("session");
    expect(response.headers.get("cache-control")).toContain("no-store");
    expect(response.headers.get("location")).toBeNull();
  });

  it("rejects malformed tokens and cross-origin requests", async () => {
    for (const value of ["", "xyz", "abc\n", "a".repeat(257), null, 123]) {
      expect((await POST(request({ token_hash: value }))).status).toBe(400);
    }
    expect((await POST(request({ token_hash: token }, "https://evil.example"))).status).toBe(403);
    expect((await POST(request({ token_hash: token, next: "https://evil.example" }))).status).toBe(400);
    expect(mocks.verifyOtp).not.toHaveBeenCalled();
  });

  it("does not replace an existing authenticated identity", async () => {
    mocks.getUser.mockResolvedValueOnce({ data: { user: { id: "another-user" } }, error: null });
    const response = await POST(request({ token_hash: token }));
    expect(response.status).toBe(409);
    expect(mocks.verifyOtp).not.toHaveBeenCalled();
  });

  it("rejects expired and already used invitations without exposing provider errors", async () => {
    mocks.verifyOtp.mockResolvedValue({ error: { message: "secret provider detail" } });
    for (let i = 0; i < 2; i++) {
      const response = await POST(request({ token_hash: token }));
      expect(response.status).toBe(400);
      expect(await response.json()).toEqual({ error: "invalid_link" });
      expect(response.headers.get("location")).toBeNull();
    }
  });
});
